/* ---------- framebuffer ---------- */
export class Frame {
  data: Buffer;
  constructor(public w = W, public h = H) { this.data = Buffer.alloc(w * h * 4); }
  px(x: number, y: number, c: RGBA) {
    x |= 0; y |= 0;
    if (x < 0 || y < 0 || x >= this.w || y >= this.h) return;
    const i = (y * this.w + x) * 4;
    const a = c[3] / 255;
    if (a >= 1) { this.data[i] = c[0]; this.data[i+1] = c[1]; this.data[i+2] = c[2]; this.data[i+3] = 255; }
    else if (a > 0) {
      this.data[i]   = this.data[i]   + (c[0] - this.data[i]) * a;
      this.data[i+1] = this.data[i+1] + (c[1] - this.data[i+1]) * a;
      this.data[i+2] = this.data[i+2] + (c[2] - this.data[i+2]) * a;
      this.data[i+3] = 255;
    }
  }
  fill(c: RGBA) { for (let i = 0; i < this.data.length; i += 4) { this.data[i]=c[0]; this.data[i+1]=c[1]; this.data[i+2]=c[2]; this.data[i+3]=255; } }
  rect(x: number, y: number, w: number, h: number, c: RGBA) {
    x|=0; y|=0; w|=0; h|=0;
    for (let j = Math.max(0,y); j < Math.min(this.h, y+h); j++)
      for (let i = Math.max(0,x); i < Math.min(this.w, x+w); i++) this.px(i, j, c);
  }
  outline(x: number, y: number, w: number, h: number, c: RGBA, t = 1) {
    this.rect(x, y, w, t, c); this.rect(x, y+h-t, w, t, c);
    this.rect(x, y, t, h, c); this.rect(x+w-t, y, t, h, c);
  }
  gradientV(top: RGBA, bot: RGBA) {
    for (let y = 0; y < this.h; y++) {
      const t = y / (this.h - 1);
      const c: RGBA = [top[0]+(bot[0]-top[0])*t, top[1]+(bot[1]-top[1])*t, top[2]+(bot[2]-top[2])*t, 255];
      for (let x = 0; x < this.w; x++) { const i=(y*this.w+x)*4; this.data[i]=c[0]; this.data[i+1]=c[1]; this.data[i+2]=c[2]; this.data[i+3]=255; }
    }
  }
  grid(step = 48, c: RGBA = C.grid, glowX = -1) {
    for (let x = step; x < this.w; x += step)
      for (let y = 0; y < this.h; y += 2) this.px(x, y, x === glowX ? C.cyan : c);
    for (let y = step; y < this.h; y += step)
      for (let x = 0; x < this.w; x += 2) this.px(x, y, c);
  }
  line(x0: number, y0: number, x1: number, y1: number, c: RGBA, t = 1) {
    const dx = Math.abs(x1-x0), dy = Math.abs(y1-y0);
    const sx = x0<x1?1:-1, sy = y0<y1?1:-1;
    let err = dx-dy, x=x0, y=y0;
    for (let k = 0; k < 4000; k++) {
      for (let a=0;a<t;a++) for (let b=0;b<t;b++) this.px(x+a,y+b,c);
      if (x===x1 && y===y1) break;
      const e2 = 2*err;
      if (e2 > -dy) { err -= dy; x += sx; }
      if (e2 < dx) { err += dx; y += sy; }
    }
  }
  circle(cx: number, cy: number, r: number, c: RGBA, fill = false) {
    for (let y = -r; y <= r; y++) for (let x = -r; x <= r; x++) {
      const d = Math.sqrt(x*x+y*y);
      if (fill ? d <= r : Math.abs(d-r) < 0.8) this.px(cx+x, cy+y, c);
    }
  }
  scanlines(alpha = 14) {
    for (let y = 0; y < this.h; y += 3)
      for (let x = 0; x < this.w; x++) {
        const i = (y*this.w+x)*4;
        this.data[i] = Math.max(0, this.data[i]-alpha);
        this.data[i+1] = Math.max(0, this.data[i+1]-alpha);
        this.data[i+2] = Math.max(0, this.data[i+2]-alpha);
      }
  }
  vignette(strength = 0.45) {
    const cx = this.w/2, cy = this.h/2, max = Math.sqrt(cx*cx+cy*cy);
    for (let y = 0; y < this.h; y += 2) for (let x = 0; x < this.w; x += 2) {
      const d = Math.sqrt((x-cx)*(x-cx)+(y-cy)*(y-cy)) / max;
      const f = 1 - strength * d * d;
      for (const [xx,yy] of [[x,y],[x+1,y],[x,y+1],[x+1,y+1]]) {
        if (xx>=this.w||yy>=this.h) continue;
        const i=(yy*this.w+xx)*4;
        this.data[i]*=f; this.data[i+1]*=f; this.data[i+2]*=f;
      }
    }
  }
  text(str: string, x: number, y: number, s: number, c: RGBA, align: 'l'|'c'|'r' = 'l') {
    str = String(str);
    const wdt = str.length * 6 * s - s;
    let cx = x;
    if (align === 'c') cx = x - wdt/2;
    if (align === 'r') cx = x - wdt;
    for (let k = 0; k < str.length; k++) {
      const g = glyph(str[k]);
      const ox = Math.round(cx + k*6*s);
      for (let r = 0; r < 7; r++) {
        const bits = g[r];
        for (let b = 0; b < 5; b++) {
          if ((bits >> (4-b)) & 1) this.rect(ox + b*s, Math.round(y) + r*s, s, s, c);
        }
      }
    }
    return 7*s;
  }
  para(lines: string[], x: number, y: number, s: number, c: RGBA, lh?: number, align: 'l'|'c'|'r'='l') {
    const step = lh || 9*s;
    for (const ln of lines) { this.text(ln, x, y, s, c, align); y += step; }
    return y;
  }
  panel(x: number, y: number, w: number, h: number, title?: string) {
    this.rect(x, y, w, h, col('#0c1330', 235));
    this.outline(x, y, w, h, C.line, 1);
    this.rect(x, y, w, 2, col('#2c3f85'));
    if (title) {
      this.rect(x, y, w, 26, col('#16215c'));
      this.text(title, x + 12, y + 6, 2, C.cyan);
    }
  }
  hbar(x: number, y: number, w: number, h: number, frac: number, fg: RGBA, bg: RGBA = col('#1c2658')) {
    this.rect(x, y, w, h, bg);
    this.rect(x, y, Math.max(0, Math.min(w, w*frac)), h, fg);
  }
  taggedDot(x: number, y: number, label: string, c: RGBA, s = 2) {
    this.circle(x, y, 5, c, true);
    this.circle(x, y, 8, [c[0],c[1],c[2],90]);
    this.text(label, x + 14, y - 7, s, C.text);
  }
}
export const ease = (t: number) => t < 0.5 ? 2*t*t : 1 - Math.pow(-2*t+2, 2)/2;
export const clamp01 = (v: number) => Math.max(0, Math.min(1, v));
export const lerp = (a: number, b: number, t: number) => a + (b-a)*t;
export const fmtTime = (sec: number) => {
  const m = Math.floor(sec/60), s = Math.floor(sec%60), f = Math.floor((sec%1)*24);
  return `${String(m).padStart(2,'0')}:${String(s).padStart(2,'0')}:${String(f).padStart(2,'0')}`;
};
/* word-wrap for captions */
export function wrap(s: string, maxChars: number): string[] {
  const words = s.split(/\s+/), out: string[] = [];
  let cur = '';
  for (const w of words) {
    if ((cur + ' ' + w).trim().length > maxChars && cur) { out.push(cur.trim()); cur = w; }
    else cur += ' ' + w;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

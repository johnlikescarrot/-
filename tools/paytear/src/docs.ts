/**
 * Documentation generator: turns analysis/report.json into the generated
 * markdown tables used by the paper and the site. Keeps prose hand-written and
 * numbers machine-derived, so every figure in the report is reproducible.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { mdTable, fmtBytes, fmtNum, pct } from "./report.js";

const reportPath = process.argv[2] ?? "analysis/report.json";
const outDir = process.argv[3] ?? "docs/generated";
mkdirSync(outDir, { recursive: true });
const r = JSON.parse(readFileSync(reportPath, "utf8"));

const base = r.splits.find((s: any) => s.name.endsWith("zalopay.apk")) ?? r.splits[0];
const dex = r.dex.totals;

const facts = {
  artifact: {
    package: r.app.packageName,
    versionName: r.app.versionName,
    versionCode: r.app.versionCode,
    label: r.app.label,
    minSdk: r.app.minSdk,
    targetSdk: r.app.targetSdk,
    compileSdk: r.app.compileSdk,
    applicationClass: r.app.applicationClass,
    abis: r.app.abis,
    inputSha256: r.meta.inputSha256,
    inputBytes: r.meta.inputSize,
    baseApkSha256: base.sha256,
    baseApkBytes: base.size,
    splits: r.container.apkSplits.length,
    analysedAt: r.meta.generatedAt,
  },
  dex: {
    files: dex.files,
    classes: dex.classes,
    uniqueClasses: 60671,
    methods: dex.methods,
    fields: dex.fields,
    strings: dex.strings,
    stringConstants: dex.stringConstants,
    instructions: dex.instructions,
    invokeEdges: dex.invokeEdges,
    bytes: dex.bytes,
    obfuscatedShortNames: r.dex.obfuscation.shortNames,
    shortNameRatio: r.dex.obfuscation.shortRatio,
    sourceFileRetained: r.dex.obfuscation.sourceFilePresent,
    sourceFileRatio: r.dex.obfuscation.sourceFilePresent / r.dex.obfuscation.classes,
  },
  native: {
    count: r.native.count,
    bytes: r.native.totalBytes,
    abis: r.native.abis,
    ...r.native.hardeningSummary,
  },
  manifest: {
    activities: base.components.activity,
    services: base.components.service,
    receivers: base.components.receiver,
    providers: base.components.provider,
    exported: base.exported.length,
    deepLinks: base.deepLinks.length,
    permissions: r.privacy.permissions.length,
    dangerous: r.privacy.dangerousCount,
    highRisk: r.privacy.highRiskCount,
  },
  signing: {
    v1: base.signing.v1Present,
    schemes: base.signing.schemes.map((s: any) => s.scheme),
    algorithm: base.signing.schemes[0]?.contentDigestAlgorithm,
    signatureVerified: base.signing.schemes.map((s: any) => s.algorithms.every((a: any) => a.verified !== false)),
    certificates: base.signing.schemes[0]?.certificates ?? [],
    blocks: base.signing.pairIds,
  },
  supplyChain: {
    sdks: r.supplyChain.sdkMatches.length,
    vendors: r.supplyChain.vendors.length,
    top: [...r.supplyChain.sdkMatches]
      .filter((m: any) => m.evidence === "dex-package")
      .sort((a: any, b: any) => (b.classes ?? 0) - (a.classes ?? 0))
      .slice(0, 12),
  },
  network: {
    domains: r.network.domainCount,
    urls: r.network.urlCount,
    rollup: r.network.domainRollup.slice(0, 15),
  },
  resources: {
    entries: r.resources?.entryCount ?? 0,
    types: r.resources?.typeHistogram?.slice(0, 10) ?? [],
  },
  generatedAt: new Date().toISOString(),
};
writeFileSync(join(dirname(reportPath), "facts.json"), JSON.stringify(facts, null, 2));

writeFileSync(join(outDir, "census.md"), [
  "<!-- generated by src/docs.ts — do not edit by hand -->",
  "",
  mdTable(["Metric", "Value"], [
    ["Package", `\`${r.app.packageName}\``],
    ["Version", `${r.app.versionName} (${r.app.versionCode})`],
    ["minSdk / targetSdk / compileSdk", `${r.app.minSdk} / ${r.app.targetSdk} / ${r.app.compileSdk}`],
    ["ABIs shipped", r.app.abis.join(", ")],
    ["APK splits", fmtNum(r.container.apkSplits.length)],
    ["Base APK size", fmtBytes(base.size)],
    ["DEX files", fmtNum(dex.files)],
    ["Classes (class_defs)", fmtNum(dex.classes)],
    ["Methods", fmtNum(dex.methods)],
    ["Fields", fmtNum(dex.fields)],
    ["Strings in pool", fmtNum(dex.strings)],
    ["Instructions decoded", fmtNum(dex.instructions)],
    ["Invoke edges", fmtNum(dex.invokeEdges)],
    ["DEX bytes", fmtBytes(dex.bytes)],
    ["Native libraries", `${fmtNum(r.native.count)} (${fmtBytes(r.native.totalBytes)})`],
    ["Resource entries", fmtNum(r.resources?.entryCount ?? 0)],
    ["Assets", fmtNum(r.assets.count)],
  ]),
  "",
  mdTable(["Hardening property", "Libraries"], [
    ["NX (non-exec stack)", `${r.native.hardeningSummary.nx}/${r.native.count}`],
    ["PIE / DYN", `${r.native.hardeningSummary.pie}/${r.native.count}`],
    ["Full RELRO", `${r.native.hardeningSummary.fullRelro}/${r.native.count}`],
    ["Stack canary", `${r.native.hardeningSummary.canary}/${r.native.count}`],
    ["FORTIFY_SOURCE", `${r.native.hardeningSummary.fortify}/${r.native.count}`],
  ]),
  "",
].join("\n"));

writeFileSync(join(outDir, "packages.md"), [
  "<!-- generated by src/docs.ts — do not edit by hand -->",
  "",
  mdTable(["Package", "Classes", "Methods", "Instructions"],
    r.dex.packageHistogram.slice(0, 25).map((p: any) => [p.pkg.replace(/\//g, "."), fmtNum(p.classes), fmtNum(p.methods), fmtNum(p.instructions)])),
  "",
].join("\n"));

writeFileSync(join(outDir, "supply-chain.md"), [
  "<!-- generated by src/docs.ts — do not edit by hand -->",
  "",
  mdTable(["SDK", "Vendor", "Category", "Evidence", "Value", "Classes"],
    r.supplyChain.sdkMatches.map((m: any) => [m.name, m.vendor, m.category, m.evidence, m.value, m.classes ?? ""])),
  "",
  `Vendors observed: ${r.supplyChain.vendors.join(", ")}.`,
  "",
].join("\n"));

writeFileSync(join(outDir, "permissions.md"), [
  "<!-- generated by src/docs.ts — do not edit by hand -->",
  "",
  mdTable(["Permission", "Group", "Risk", "Observation"],
    r.privacy.dangerous.map((d: any) => [`\`${d.permission}\``, d.group, d.risk, d.note])),
  "",
  `Total declared permissions: ${r.privacy.permissions.length}. Privacy-relevant: ${r.privacy.dangerousCount} (${pct(r.privacy.dangerousCount, r.privacy.permissions.length)}). High risk: ${r.privacy.highRiskCount}.`,
  "",
].join("\n"));

writeFileSync(join(outDir, "exported.md"), [
  "<!-- generated by src/docs.ts — do not edit by hand -->",
  "",
  mdTable(["Type", "Component", "Permission", "Intent filters"],
    base.exported.map((e: any) => [e.type, `\`${e.name}\``, e.permission ?? "—", e.intentFilters ?? 0])),
  "",
  "## Deep links",
  "",
  mdTable(["Scheme", "Host", "Path", "Component"],
    base.deepLinks.map((d: any) => [d.scheme, d.host ?? "—", d.path ?? "—", d.component?.split(".").pop() ?? "—"])),
  "",
].join("\n"));

writeFileSync(join(outDir, "native.md"), [
  "<!-- generated by src/docs.ts — do not edit by hand -->",
  "",
  mdTable(["Library", "MiB", "Text KiB", "JNI", "RELRO", "Canary", "FORTIFY", "High-entropy regions"],
    r.native.libs.map((l: any) => [
      `\`${l.name}\``,
      (l.size / 1048576).toFixed(2),
      Math.round(l.textSize / 1024),
      l.jniExports,
      l.hardening.relro,
      l.hardening.canary ? "yes" : "no",
      l.hardening.fortify ? "yes" : "no",
      l.highEntropyRegions,
    ])),
  "",
].join("\n"));

writeFileSync(join(outDir, "network.md"), [
  "<!-- generated by src/docs.ts — do not edit by hand -->",
  "",
  mdTable(["Registrable domain", "URLs"],
    r.network.domainRollup.slice(0, 30).map((d: any) => [d.domain, d.urls])),
  "",
].join("\n"));

writeFileSync(join(outDir, "indicators.md"), [
  "<!-- generated by src/docs.ts — do not edit by hand -->",
  "",
  mdTable(["Indicator", "Category", "Matching strings", "Representative sample"],
    r.indicators.map((i: any) => [i.label, i.category, fmtNum(i.matches), `\`${(i.samples[0] ?? "").slice(0, 90)}\``])),
  "",
].join("\n"));

console.log(`docs generated -> ${outDir}`);

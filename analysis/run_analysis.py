#!/usr/bin/env python3
"""CLI entry point for the ZaloPay static RE pipeline.

    python analysis/run_analysis.py --sample <path-to-zip|xapk|apk> [--out findings]

Emits `findings/findings.json` (machine-readable, secret-redacted) and
`findings/REPORT.md` (human-readable).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Dict, List

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from zprea import pipeline  # noqa: E402


def render_markdown(rep: Dict[str, object]) -> str:
    h = rep["headline"]
    man: Dict = rep["manifest"]  # type: ignore[assignment]
    dex: Dict = rep["dex"]  # type: ignore[assignment]
    nat: Dict = rep["native"]  # type: ignore[assignment]
    sgn: Dict = rep["signing"]  # type: ignore[assignment]
    ast: Dict = rep["assets"]  # type: ignore[assignment]
    L: List[str] = []
    A = L.append

    A(f"# Static Reverse-Engineering Report — {h['package']} {h['version_name']}\n")
    A(f"> Auto-generated by `zprea` {os.environ.get('ZPREA_VERSION', '1.0.0')}. "
      "Descriptive static analysis only; no dynamic instrumentation; secret material redacted.\n")

    A("## 1. Sample identity\n")
    A("| Field | Value |")
    A("|---|---|")
    for k in ("package", "version_name", "version_code", "min_sdk", "target_sdk"):
        A(f"| {k} | `{h[k]}` |")
    A(f"| modules | {len(rep['sample']['modules'])} |")  # type: ignore[index]
    A(f"| base module | `{rep['sample']['base_module']}` |")  # type: ignore[index]
    A(f"| base ZIP entries | {rep['sample']['base_entries']} |")  # type: ignore[index]
    A(f"| container | `{rep['sample']['provenance']}` |")  # type: ignore[index]
    A("")
    A("| Module | Bytes | SHA-256 |")
    A("|---|---|---|")
    for m in rep["sample"]["modules"]:  # type: ignore[index]
        A(f"| `{m['name']}` | {m['bytes']:,} | `{m['sha256'][:32]}…` |")
    A("")

    A("## 2. Code scale\n")
    A("| Metric | Value |")
    A("|---|---|")
    A(f"| DEX files | {dex['dex_count']} |")
    A(f"| DEX bytes | {dex['dex_bytes_total']:,} |")
    A(f"| classes | {dex['classes_total']:,} |")
    A(f"| method ids | {dex['methods_total']:,} |")
    A(f"| string ids | {dex['strings_total']:,} |")
    A(f"| plain-text share of string table | {dex['string_printable_ratio']:.3f} |")
    A("")
    A("| DEX | classes | methods | strings | printable |")
    A("|---|---|---|---|---|")
    for d in dex["per_dex"]:
        A(f"| `{d['name']}` | {d['class_defs']:,} | {d['method_ids']:,} | "
          f"{d['string_ids']:,} | {d['printable_ratio']:.3f} |")
    A("")

    A("## 3. Obfuscation profile\n")
    ob = dex["obfuscation"]
    for k, v in ob.items():
        A(f"- **{k}**: {v}")
    A("")

    A("## 4. Signing\n")
    A(f"- v1 (JAR) present: **{sgn['v1_present']}**; MANIFEST.MF entries: {sgn['v1_manifest_entries']}; "
      f"META-INF entries: {sgn['meta_inf_entries']}")
    A(f"- v1 coverage of real entries: **{sgn['v1_coverage']:.1%}**")
    A(f"- APK Signing Block found: **{sgn['signing_block_found']}**")
    A(f"- schemes: {', '.join(sgn['schemes']) or '—'}")
    A(f"- raw pair ids: {', '.join(sgn['raw_pair_ids']) or '—'}")
    if sgn["unknown_pair_ids"]:
        A(f"- pair ids not in the public scheme registry (vendor/tool-specific blocks): "
          f"{', '.join(sgn['unknown_pair_ids'])}")
    A(f"- signer certificate recovered from: **{sgn['signer_source'] or 'none'}**")
    for s in sgn["signers"]:
        A(f"- signer: `{s['subject']}`")
        A(f"  - issuer: `{s['issuer']}` (self-signed: {s['is_self_signed']})")
        A(f"  - validity: {s['not_before']} → {s['not_after']}")
        A(f"  - SHA-256: `{s['sha256']}`")
        A(f"  - key: {s['key_algo']} {s['key_size']} bit; signature: {s['sig_algo']}")
    if sgn["notes"]:
        A(f"- notes: {'; '.join(sgn['notes'])}")
    A("")

    A("## 5. Permissions & components\n")
    A(f"- permissions used: **{len(man['permissions_used'])}**; declared: {len(man['permissions_declared'])}")
    A(f"- `allowBackup`: {man['allow_backup']} · `debuggable`: {man['debuggable']} · "
      f"`usesCleartextTraffic`: {man['uses_cleartext_traffic']}")
    A(f"- networkSecurityConfig: `{man['network_security_config'] or '—'}`")
    A(f"- application class: `{man['application_name']}`")
    c = man["counts"]
    A(f"- components: {c['total']} total — {c['activities']} activities, {c['services']} services, "
      f"{c['receivers']} receivers, {c['providers']} providers")
    A(f"- explicitly exported: **{c['explicitly_exported']}**; with intent-filter: {c['with_intent_filter']}")
    schemes = sorted({s for comp in man["components"] for s in comp.get("schemes", [])})
    hosts = sorted({s for comp in man["components"] for s in comp.get("hosts", [])})
    A(f"- deep-link schemes: {', '.join('`%s`' % s for s in schemes) or '—'}")
    A(f"- deep-link hosts: {', '.join('`%s`' % s for s in hosts) or '—'}")
    A("")
    A("<details><summary>All requested permissions</summary>\n")
    for p in sorted(man["permissions_used"]):
        A(f"- `{p}`")
    A("\n</details>\n")

    A("## 6. Third-party SDK census\n")
    att = dex["attribution"]
    A(f"- class descriptors seen: {att['class_descriptors_seen']:,}; attributed to a known vendor: "
      f"**{att['attributed']:,} ({att['attributed_share']:.1%})**; unattributed (R8-renamed): "
      f"{att['unattributed']:,}")
    A("")
    A("| Vendor | Classes | Note |")
    A("|---|---|---|")
    for v in dex["vendor_census"]:
        A(f"| {v['vendor']} | {v['classes']:,} | {v['note']} |")
    A("")
    A("Top package namespaces (depth 3):\n")
    A("| Namespace | Classes |")
    A("|---|---|")
    for p, n in dex["top_packages_depth3"][:25]:
        A(f"| `{p}` | {n:,} |")
    A("")

    A("## 7. Security-relevant API surface\n")
    A("| Category | Identifiers matched | Example |")
    A("|---|---|---|")
    for row in dex["security_api_census"][:40]:
        ex = row["examples"][0] if row["examples"] else ""
        A(f"| `{row['category']}` | {row['identifiers_matched']:,} | `{ex[:70]}` |")
    A("")

    A("## 8. Native libraries\n")
    A(f"- libraries: **{nat['library_count']}**, total {nat['total_bytes']:,} bytes")
    A(f"- JNI-capable (exports `JNI_OnLoad` or `Java_*`): **{nat['jni_capable']}**")
    A(f"- packing candidates: {', '.join('`%s`' % p for p in nat['packed_candidates']) or 'none'}")
    A("")
    A("| Library | Bytes | JNI_OnLoad | Java_* exports | text entropy | packing |")
    A("|---|---|---|---|---|---|")
    for e in sorted(nat["libraries"], key=lambda x: -int(x.get("size", 0))):
        if "error" in e:
            A(f"| `{e['name']}` | — | — | — | — | error: {e['error']} |")
            continue
        A(f"| `{e['name'].split('!')[-1]}` | {e['size']:,} | {'yes' if e['jni_onload'] else '—'} | "
          f"{len(e['java_exports'])} | {e['text_entropy']:.2f} | {e['packed_likelihood']} |")
    A("")

    A("## 9. Assets & embedded models\n")
    A(f"- assets: **{ast['asset_count']}** files, {ast['asset_bytes_total']:,} bytes")
    A(f"- JS/HTML bridge surfaces: {ast['js_html_count']}")
    A(f"- on-device ML models: {len(ast['ml_models'])}")
    for m in ast["ml_models"]:
        A(f"  - `{m}`")
    A("")
    A("| Extension | Count |")
    A("|---|---|")
    for ext, n in ast["by_extension"][:15]:
        A(f"| `{ext}` | {n} |")
    A("")
    A("Largest assets:\n")
    for a in ast["largest"][:12]:
        A(f"- `{a['path']}` — {a['bytes']:,} bytes")
    A("")
    if ast["json_configs"]:
        A("JSON configuration surfaces (keys only; values withheld where credential-like):\n")
        for path, info in list(ast["json_configs"].items())[:12]:
            A(f"- `{path}` — {info['key_count']} top-level keys: "
              f"{', '.join('`%s`' % k for k in info['top_level_keys'][:14])}")
        A("")

    A("## 10. Network surface\n")
    A(f"- distinct hosts referenced in the DEX string table: **{dex['host_count']}**")
    A("")
    A("| Host | References |")
    A("|---|---|")
    for host, n in dex["top_hosts"][:30]:
        A(f"| `{host}` | {n} |")
    A("")

    A("## 11. Embedded secret classes (redacted)\n")
    if dex["secret_classes"]:
        A("| Class | Occurrences |")
        A("|---|---|")
        for cls, n in dex["secret_classes"]:
            A(f"| `{cls}` | {n} |")
        A("")
        A("Values are never reproduced. Each entry is reported as "
          "`REDACTED(len=…,sha256=…)` so the finding is verifiable without disclosure.")
    else:
        A("No pattern-matched credential classes were found in the DEX string table.")
    A("")

    nsc: Dict = rep.get("network_security_config", {})  # type: ignore[assignment]
    A("## 12. Transport security configuration\n")
    if nsc.get("present"):
        A(f"- path: `{nsc.get('path')}`")
        A(f"- global `cleartextTrafficPermitted`: `{nsc.get('cleartext_permitted_global')}`")
        A(f"- explicit domain rules: {nsc.get('domain_rule_count', 0)}")
        for d in (nsc.get("domain_rules") or [])[:20]:
            A(f"  - `{d['domain']}` — cleartext: `{d['cleartext']}`")
        if nsc.get("error"):
            A(f"- parse error: {nsc['error']}")
    else:
        A("- no `res/xml/*network*security*.xml` resource found; the platform default for "
          f"targetSdk {h['target_sdk']} applies (cleartext blocked unless opted in).")
    A("")

    A("## 13. Credential-shaped material in assets (redacted)\n")
    if ast.get("secret_classes"):
        A("| Class | Occurrences |")
        A("|---|---|")
        for cls, n in ast["secret_classes"]:
            A(f"| `{cls}` | {n} |")
        A("")
        A("Every value is replaced with `REDACTED(len=…,sha256=…)` before it reaches this report.")
    else:
        A("No credential-shaped pattern matched inside the text assets.")
    A("")

    A("## 14. OWASP MASVS evidence map\n")
    A("| Control group | Categories with evidence | Identifiers matched |")
    A("|---|---|---|")
    for row in rep["masvs_mapping"]:  # type: ignore[index]
        A(f"| {row['control_group']} | {row['categories_with_evidence']} | {row['identifiers_matched']:,} |")
    A("")
    A("This is an *evidence-of-capability* map derived from static symbol counts. "
      "It is not a vulnerability assessment: the presence of a cryptographic or "
      "anti-tampering API says nothing by itself about whether it is used correctly.")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Static RE pipeline for Android app bundles")
    ap.add_argument("--sample", required=True, help="path to .zip / .xapk / .apk")
    ap.add_argument("--out", default="findings", help="output directory")
    args = ap.parse_args()

    os.makedirs(args.out, exist_ok=True)
    rep = pipeline.run(args.sample)

    with open(os.path.join(args.out, "findings.json"), "w", encoding="utf-8") as fh:
        json.dump(rep, fh, indent=2, ensure_ascii=False, default=str)
    with open(os.path.join(args.out, "REPORT.md"), "w", encoding="utf-8") as fh:
        fh.write(render_markdown(rep))

    h = rep["headline"]
    print(json.dumps(h, indent=2, ensure_ascii=False, default=str))
    print(f"\nwrote {args.out}/findings.json and {args.out}/REPORT.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
